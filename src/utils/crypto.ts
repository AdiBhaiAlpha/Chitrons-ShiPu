import crypto from 'crypto';
import fs from 'fs';
import path from 'path';

const keyPath = path.join(process.cwd(), 'config', 'encryption.key');

function getEncryptionKey(): Buffer {
  // Priority 1: Environment variable explicit key or app secret
  const envSecret = process.env.ENCRYPTION_KEY || process.env.APP_SECRET;
  if (envSecret && envSecret.trim().length > 0) {
    return crypto.createHash('sha256').update(envSecret.trim()).digest();
  }

  // Priority 2: File-based saved key
  if (fs.existsSync(keyPath)) {
    try {
      const savedKey = fs.readFileSync(keyPath);
      if (savedKey.length === 32) return savedKey;
    } catch (e) {
      // Ignore read error
    }
  }

  // Priority 3: Stable deterministic default secret key
  // Guarantees consistent encryption/decryption across container restarts and reboots
  const defaultSecret = 'ShipuAi_Global_Encryption_Secret_Key_v2.5_2026_Secure';
  const key = crypto.createHash('sha256').update(defaultSecret).digest();

  try {
    if (!fs.existsSync(path.dirname(keyPath))) {
      fs.mkdirSync(path.dirname(keyPath), { recursive: true });
    }
    fs.writeFileSync(keyPath, key);
  } catch (e) {
    // Ignore write error in read-only filesystems
  }
  return key;
}

const ENCRYPTION_KEY = getEncryptionKey(); // 32 bytes
const ALGORITHM = 'aes-256-gcm';

export function encrypt(text: string): string {
  if (!text) return text;
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv(ALGORITHM, ENCRYPTION_KEY, iv);
  let encrypted = cipher.update(text, 'utf8', 'hex');
  encrypted += cipher.final('hex');
  const authTag = cipher.getAuthTag();
  return `${iv.toString('hex')}:${encrypted}:${authTag.toString('hex')}`;
}

export function decrypt(text: string): string {
  if (!text) return text;
  
  const trimmed = text.trim();
  // Fast path: JSON arrays or objects are unencrypted plain text
  if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
    return text;
  }

  if (!trimmed.includes(':')) {
    return text; // Unencrypted plain string
  }

  const parts = trimmed.split(':');
  // AES-256-GCM encrypted format must be exactly 3 hex parts: IV (12 bytes = 24 hex chars), Ciphertext (hex), AuthTag (16 bytes = 32 hex chars)
  if (parts.length !== 3) {
    return text;
  }

  const ivHex = parts[0];
  const encryptedText = parts[1];
  const authTagHex = parts[2];

  // Validate hex format and lengths
  const is24Hex = /^[0-9a-fA-F]{24}$/.test(ivHex);
  const is32Hex = /^[0-9a-fA-F]{32}$/.test(authTagHex);
  const isHexText = /^[0-9a-fA-F]*$/.test(encryptedText);

  if (!is24Hex || !is32Hex || !isHexText) {
    return text; // Not ciphertext generated by encrypt()
  }

  try {
    const iv = Buffer.from(ivHex, 'hex');
    const authTag = Buffer.from(authTagHex, 'hex');
    const decipher = crypto.createDecipheriv(ALGORITHM, ENCRYPTION_KEY, iv);
    decipher.setAuthTag(authTag);
    let decrypted = decipher.update(encryptedText, 'hex', 'utf8');
    decrypted += decipher.final('utf8');
    return decrypted;
  } catch (err: any) {
    // Graceful fallback for legacy encrypted data or corrupted strings
    return text;
  }
}

export const encryptPassword = encrypt;
export const decryptPassword = decrypt;
export const encryptAuthState = encrypt;
export const decryptAuthState = decrypt;

